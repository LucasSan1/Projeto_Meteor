DROP TABLE IF EXISTS historicoProducao CASCADE;
DROP TABLE IF EXISTS historicoManutencao CASCADE;
DROP TABLE IF EXISTS manutencoesProgramadas CASCADE;
DROP TABLE IF EXISTS maquinas CASCADE;
DROP TABLE IF EXISTS equipamentos CASCADE;
DROP TABLE IF EXISTS movimentacoesEstoque CASCADE;
DROP TABLE IF EXISTS historicoOrdens CASCADE;
DROP TABLE IF EXISTS rejeicoes CASCADE;
DROP TABLE IF EXISTS inspecoes CASCADE;
DROP TABLE IF EXISTS ordemMateriais CASCADE;
DROP TABLE IF EXISTS ordensProducao CASCADE;
DROP TABLE IF EXISTS pecas CASCADE;
DROP TABLE IF EXISTS materiasPrimas CASCADE;
DROP TABLE IF EXISTS fornecedores CASCADE;
DROP TABLE IF EXISTS profissionais CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;

-- Os tipos ENUM também precisam morrer antes de renascer
DROP TYPE IF EXISTS cargo_usuario CASCADE;
DROP TYPE IF EXISTS status_registro CASCADE;
DROP TYPE IF EXISTS tipo_movimentacao CASCADE;
DROP TYPE IF EXISTS status_ordem_producao CASCADE;
DROP TYPE IF EXISTS tipo_rejeicao CASCADE;
DROP TYPE IF EXISTS status_rejeicao CASCADE;
DROP TYPE IF EXISTS status_manutencao CASCADE;


-- ============================================================
--  TIPOS (os ENUM do MySQL, agora cidadãos de primeira classe)
-- ============================================================

CREATE TYPE cargo_usuario AS ENUM ('gerente', 'operador', 'mecanico');

CREATE TYPE status_registro AS ENUM ('Ativo', 'Desativado');

CREATE TYPE tipo_movimentacao AS ENUM ('Entrada', 'Saida');

CREATE TYPE status_ordem_producao AS ENUM ('Pendente', 'Em Produção', 'Concluída', 'Cancelada');

CREATE TYPE tipo_rejeicao AS ENUM ('Retrabalho', 'Perda');

CREATE TYPE status_rejeicao AS ENUM ('Pendente', 'Concluído');

CREATE TYPE status_manutencao AS ENUM ('Programada', 'Em Execução', 'Concluída', 'Cancelada');


-- ============================================================
--  PESSOAS
-- ============================================================

-- Identidade de quem entra no sistema (gestor, operador ou mecânico)
CREATE TABLE usuarios (
    id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(100) NOT NULL,
    email   VARCHAR(200) UNIQUE NOT NULL,
    cargo   cargo_usuario NOT NULL DEFAULT 'operador',
    senha   VARCHAR(200) NOT NULL,
    status  status_registro NOT NULL DEFAULT 'Ativo'
);

-- Profissionais alocáveis: UMA linha por pessoa, com flags dos papéis
-- Quem é operador E mecânico tem identidade única, então o limite de
-- "1 atividade por dia" vale pra todas as atribuições (nada de clonar gente)
-- O gerente NÃO entra aqui: ele gerencia, não é alocado
CREATE TABLE profissionais (
    pk_profissionalID   INT GENERATED BY DEFAULT AS IDENTITY,
    fk_usuarioID        INT NOT NULL,
    ehOperador          SMALLINT NOT NULL DEFAULT 0,
    ehMecanico          SMALLINT NOT NULL DEFAULT 0,
    especializacao      VARCHAR(100),
    telefone            VARCHAR(50),
    status              status_registro NOT NULL DEFAULT 'Ativo',

    PRIMARY KEY (pk_profissionalID),
    UNIQUE (fk_usuarioID),
    FOREIGN KEY (fk_usuarioID) REFERENCES usuarios(id),
    CONSTRAINT chkProfissionalFuncao CHECK (ehOperador = 1 OR ehMecanico = 1)
);


--  SUPRIMENTOS E ESTOQUE
CREATE TABLE fornecedores (
    pk_fornecedorID     INT GENERATED BY DEFAULT AS IDENTITY,
    nomeFornecedor      VARCHAR(100) NOT NULL,
    cnpj                CHAR(14) NOT NULL,
    endereco            VARCHAR(300) NOT NULL,
    contato             VARCHAR(50) NOT NULL,
    avaliacao           NUMERIC(2,1),
    status              status_registro NOT NULL DEFAULT 'Ativo',

    PRIMARY KEY (pk_fornecedorID),
    UNIQUE (cnpj)

);

CREATE TABLE materiasPrimas (
    pk_materiaID        INT GENERATED BY DEFAULT AS IDENTITY,
    materia             VARCHAR(300) NOT NULL,
    fk_fornecedor       INT NOT NULL,
    unidadeMedida       VARCHAR(20) NOT NULL,                     -- kg, m, un...
    estoqueMinimo       NUMERIC(14,3) NOT NULL DEFAULT 0,
    quantidadeEstoque   NUMERIC(14,3) NOT NULL DEFAULT 0,         -- saldo atual
    dataUltimaCompra    DATE,
    status              status_registro NOT NULL DEFAULT 'Ativo',

    PRIMARY KEY (pk_materiaID),
    FOREIGN KEY (fk_fornecedor) REFERENCES fornecedores(pk_fornecedorID),
    CONSTRAINT chkMateriaEstoque CHECK (quantidadeEstoque >= 0),  -- saldo negativo? aqui não
    CONSTRAINT chkMateriaMinimo  CHECK (estoqueMinimo >= 0)
);

-- Livro-razão do estoque: toda entrada e saída deixa rastro aqui
CREATE TABLE movimentacoesEstoque (
    pk_movimentacaoID   INT GENERATED BY DEFAULT AS IDENTITY,
    fk_materiaID        INT NOT NULL,
    tipo                tipo_movimentacao NOT NULL,
    quantidade          NUMERIC(14,3) NOT NULL,
    unidadeMedida       VARCHAR(20) NOT NULL,
    fk_usuarioID        INT NOT NULL,                             -- responsável pela operação
    fk_ordemID          INT NULL,                                 -- preenchido nas saídas (conclusão da ordem)
    dataMovimentacao    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacao          VARCHAR(300),

    PRIMARY KEY (pk_movimentacaoID),
    FOREIGN KEY (fk_materiaID) REFERENCES materiasPrimas(pk_materiaID),
    FOREIGN KEY (fk_usuarioID) REFERENCES usuarios(id),
    UNIQUE (fk_ordemID, fk_materiaID, tipo),
    CONSTRAINT chkMovQtd   CHECK (quantidade > 0),

    CONSTRAINT chkMovSaida CHECK (tipo = 'Entrada' OR fk_ordemID IS NOT NULL)
);


--  PRODUÇÃO
CREATE TABLE pecas (
    pk_pecaID       INT GENERATED BY DEFAULT AS IDENTITY,
    peca            VARCHAR(300) NOT NULL,
    peso            VARCHAR(20),
    dimensoes       VARCHAR(30),
    status          status_registro NOT NULL DEFAULT 'Ativo',

    PRIMARY KEY (pk_pecaID)
);

CREATE TABLE ordensProducao (
    pk_ordemID              INT GENERATED BY DEFAULT AS IDENTITY,
    codigo                  VARCHAR(30) NOT NULL,               
    fk_pecaID               INT NOT NULL,
    quantidadePlanejada     INT NOT NULL,
    especializacao          VARCHAR(100) NOT NULL,             
    fk_operadorID           INT NOT NULL,                      
    inicioPlanejado         TIMESTAMP NOT NULL,
    terminoPlanejado        TIMESTAMP NOT NULL,
    inicioEfetivo           TIMESTAMP NULL,                    
    conclusaoEfetiva        TIMESTAMP NULL,                     
    status                  status_ordem_producao NOT NULL DEFAULT 'Pendente',

    PRIMARY KEY (pk_ordemID),
    UNIQUE (codigo),
    FOREIGN KEY (fk_pecaID)      REFERENCES pecas(pk_pecaID),
    FOREIGN KEY (fk_operadorID)  REFERENCES profissionais(pk_profissionalID),
    CONSTRAINT chkOrdemQtd       CHECK (quantidadePlanejada > 0),
    CONSTRAINT chkOrdemPlanejado CHECK (terminoPlanejado > inicioPlanejado),
    -- A conclusão não pode chegar antes do início
    -- Por ordem da compania viagem no tempo é expressamente proibida
    CONSTRAINT chkOrdemEfetivo   CHECK (conclusaoEfetiva IS NULL OR inicioEfetivo IS NULL OR conclusaoEfetiva >= inicioEfetivo)
);


CREATE INDEX idxOrdemOperadorPeriodo ON ordensProducao (fk_operadorID, inicioPlanejado, terminoPlanejado);
CREATE INDEX idxOrdemStatus ON ordensProducao (status);

-- Materiais de cada ordem: previsto na criação, consumido efetivo na conclusão
CREATE TABLE ordemMateriais (
    pk_ordemMaterialID  INT GENERATED BY DEFAULT AS IDENTITY,
    fk_ordemID          INT NOT NULL,
    fk_materiaID        INT NOT NULL,
    quantidadePrevista  NUMERIC(14,3) NOT NULL,
    quantidadeConsumida NUMERIC(14,3) NULL,                     -- NULL até a ordem concluir

    PRIMARY KEY (pk_ordemMaterialID),
    UNIQUE (fk_ordemID, fk_materiaID),
    FOREIGN KEY (fk_ordemID)   REFERENCES ordensProducao(pk_ordemID),
    FOREIGN KEY (fk_materiaID) REFERENCES materiasPrimas(pk_materiaID),
    CONSTRAINT chkOmPrevista  CHECK (quantidadePrevista > 0),
    CONSTRAINT chkOmConsumida CHECK (quantidadeConsumida IS NULL OR quantidadeConsumida >= 0)
);

-- Auditoria de mudança de status das ordens
CREATE TABLE historicoOrdens (
    pk_historicoID  INT GENERATED BY DEFAULT AS IDENTITY,
    fk_ordemID      INT NOT NULL,
    fk_usuarioID    INT NOT NULL,
    statusAnterior  VARCHAR(50),
    statusNovo      VARCHAR(50),
    dataAlteracao   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacao      VARCHAR(300),

    PRIMARY KEY (pk_historicoID),
    FOREIGN KEY (fk_ordemID)   REFERENCES ordensProducao(pk_ordemID),
    FOREIGN KEY (fk_usuarioID) REFERENCES usuarios(id)
);



--  QUALIDADE
CREATE TABLE inspecoes (
    pk_inspecaoID   INT GENERATED BY DEFAULT AS IDENTITY,
    fk_ordemID      INT NOT NULL,
    totalProduzido  INT NOT NULL,
    aprovadas       INT NOT NULL DEFAULT 0,
    rejeitadas      INT NOT NULL DEFAULT 0,
    dataInspecao    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacoes     VARCHAR(300),

    PRIMARY KEY (pk_inspecaoID),
    UNIQUE (fk_ordemID),
    FOREIGN KEY (fk_ordemID) REFERENCES ordensProducao(pk_ordemID),
    CONSTRAINT chkInspNaoNeg CHECK (totalProduzido >= 0 AND aprovadas >= 0 AND rejeitadas >= 0),
    -- A conta tem que fechar: aprovadas + rejeitadas = produzidas (RN18)
    CONSTRAINT chkInspSoma   CHECK (aprovadas + rejeitadas = totalProduzido)
);

-- Detalha as rejeições: motivo obrigatório, ação corretiva opcional, e se foi retrabalho ou perda definitiva
CREATE TABLE rejeicoes (
    pk_rejeicaoID   INT GENERATED BY DEFAULT AS IDENTITY,
    fk_inspecaoID   INT NOT NULL,
    quantidade      INT NOT NULL,
    motivoRejeicao  VARCHAR(300) NOT NULL,
    tipo            tipo_rejeicao NOT NULL DEFAULT 'Perda',
    acoesCorretivas VARCHAR(300),
    status          status_rejeicao NOT NULL DEFAULT 'Pendente', -- acompanha a conclusão do retrabalho
    dataRejeicao    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (pk_rejeicaoID),
    FOREIGN KEY (fk_inspecaoID) REFERENCES inspecoes(pk_inspecaoID),
    CONSTRAINT chkRejQtd CHECK (quantidade > 0)
);



--  MANUTENÇÃO
CREATE TABLE equipamentos (
    pk_equipamentoID    INT GENERATED BY DEFAULT AS IDENTITY,
    nomeEquipamento     VARCHAR(100),
    descricao           VARCHAR(300),
    dataAquisicao       DATE,
    vidaUtilRestante    INT,
    status              status_registro NOT NULL DEFAULT 'Ativo',

    PRIMARY KEY (pk_equipamentoID)
);

CREATE TABLE maquinas (
    pk_maquinaID        INT GENERATED BY DEFAULT AS IDENTITY,
    fk_equipamentoID    INT NOT NULL,
    nomeMaquina         VARCHAR(100) NOT NULL,
    descricao           VARCHAR(300),
    capacidadeMaxima    VARCHAR(50) NOT NULL,
    ultimaManutencao    DATE,
    status              status_registro NOT NULL DEFAULT 'Ativo',

    PRIMARY KEY (pk_maquinaID),
    FOREIGN KEY (fk_equipamentoID) REFERENCES equipamentos(pk_equipamentoID)
);

CREATE TABLE manutencoesProgramadas (
    pk_manutencaoID     INT GENERATED BY DEFAULT AS IDENTITY,
    fk_equipamentoID    INT NOT NULL,
    fk_maquinaID        INT NULL,                               
    tipoManutencao      VARCHAR(100),
    descricao           VARCHAR(300) NOT NULL,
    especializacao      VARCHAR(100) NOT NULL,
    fk_mecanicoID       INT NOT NULL,                           
    inicioPrevisto      TIMESTAMP NOT NULL,
    terminoPrevisto     TIMESTAMP NOT NULL,
    inicioEfetivo       TIMESTAMP NULL,                        
    conclusaoEfetiva    TIMESTAMP NULL,                         
    servicosRealizados  VARCHAR(500) NULL,                      
    status              status_manutencao NOT NULL DEFAULT 'Programada',

    PRIMARY KEY (pk_manutencaoID),
    FOREIGN KEY (fk_equipamentoID) REFERENCES equipamentos(pk_equipamentoID),
    FOREIGN KEY (fk_maquinaID)     REFERENCES maquinas(pk_maquinaID),
    FOREIGN KEY (fk_mecanicoID)    REFERENCES profissionais(pk_profissionalID),
    CONSTRAINT chkManutPrevisto CHECK (terminoPrevisto > inicioPrevisto),
    CONSTRAINT chkManutEfetivo  CHECK (conclusaoEfetiva IS NULL OR inicioEfetivo IS NULL OR conclusaoEfetiva >= inicioEfetivo)
);

-- Índice pra checar sobreposição de horário do mecânico
CREATE INDEX idxManutMecanicoPeriodo ON manutencoesProgramadas (fk_mecanicoID, inicioPrevisto, terminoPrevisto);
CREATE INDEX idxManutStatus ON manutencoesProgramadas (status);

-- Um histórico por manutenção concluída
-- Agora com PK própria e a FK separada, em vez do historicoID fazendo dupla jornada de PK + FK
CREATE TABLE historicoManutencao (
    historicoID             INT GENERATED BY DEFAULT AS IDENTITY,
    fk_manutencaoID         INT NOT NULL,
    fk_equipamentoID        INT,
    fk_mecanicoID           INT NULL,                           
    manutencaoRealizada     VARCHAR(100),
    dataManutencao          DATE NOT NULL,
    inicioEfetivo           TIMESTAMP NULL,
    terminoEfetivo          TIMESTAMP NULL,
    custos                  NUMERIC(12,2) NOT NULL DEFAULT 0,  
    observacoes             VARCHAR(200),

    PRIMARY KEY (historicoID),
    UNIQUE (fk_manutencaoID),
    FOREIGN KEY (fk_manutencaoID) REFERENCES manutencoesProgramadas(pk_manutencaoID),
    FOREIGN KEY (fk_equipamentoID) REFERENCES equipamentos(pk_equipamentoID),
    CONSTRAINT fkHistoricoMecanico FOREIGN KEY (fk_mecanicoID) REFERENCES profissionais(pk_profissionalID),
    CONSTRAINT chkHistCusto CHECK (custos >= 0),
    CONSTRAINT chkHistPeriodo CHECK (terminoEfetivo IS NULL OR inicioEfetivo IS NULL OR terminoEfetivo >= inicioEfetivo)
);

-- Histórico de conclusão da produção: no máximo uma linha por ordem
CREATE TABLE historicoProducao (
    pk_historicoProducaoID  INT GENERATED BY DEFAULT AS IDENTITY,
    fk_ordemID              INT NOT NULL,
    fk_operadorID           INT NOT NULL,                       
    fk_maquinaID            INT NULL,                           
    dataConclusao           TIMESTAMP NOT NULL,
    quantidadeProduzida     INT NOT NULL,

    PRIMARY KEY (pk_historicoProducaoID),
    UNIQUE (fk_ordemID),
    FOREIGN KEY (fk_ordemID) REFERENCES ordensProducao(pk_ordemID),
    FOREIGN KEY (fk_operadorID) REFERENCES profissionais(pk_profissionalID),
    FOREIGN KEY (fk_maquinaID) REFERENCES maquinas(pk_maquinaID),
    CONSTRAINT chkHistProdQtd CHECK (quantidadeProduzida >= 0)
);



CREATE TABLE auditoria (
    pk_auditoriaID  INT GENERATED BY DEFAULT AS IDENTITY,
    fk_usuarioID    INT NOT NULL,
    entidade        VARCHAR(50) NOT NULL,       -- 'ordem', 'manutencao', 'profissional'...
    entidadeID      INT NOT NULL,
    acao            VARCHAR(50) NOT NULL,       -- 'reprogramacao', 'cancelamento', 'liberacao'...
    dadosAnteriores JSONB NULL,
    dadosNovos      JSONB NULL,
    observacao      VARCHAR(300),
    dataAcao        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (pk_auditoriaID),
    FOREIGN KEY (fk_usuarioID) REFERENCES usuarios(id)
);

CREATE INDEX idxAuditoriaEntidade ON auditoria (entidade, entidadeID);
